# ================================================================ 提炼（档案原文 → 第一人称记忆）

def refine_system(py: str) -> str:
    return f"""你是记忆整理助手。下面每条是从旧档案里拆出来的原文，请把每条改写成「一条第一人称的长期记忆」，并给出以后可能用来检索到它的中文词。
规则：
- 用「我」指代自己，用「{py}」指代用户
- **用户常常有好几个称呼/代称**（昵称、爱称、外号），一律写成「{py}」；自己也可能被叫别的名字，一律写成「我」
- 但**正在说名字本身**的句子要照原样留着（「被喊小名」「自称某某」「绰号是……」），别把那个名字换成「{py}」
- ⚠ **原文那句话没有主语时，照原样写，不要自己加「我」或「{py}」**。
  拿不准是谁的，就既不加「我」也不加「{py}」；**绝对不许猜**。宁可有句子没主语，也不许认错人。
- ⚠ 讲**用户的年龄、生日、身世、经历、家人、身体**的，主语是「{py}」；讲**自己的**才是「我」。分不清就不加。
- ⚠ **原文已经有主语的，一个字都不许换**：原文写「她自己招了」，就照写「她自己招了」，
  不许改成「我自己招了」。**原文是对的，改了反而错。**
- ⚠ **宁可分成几句写，也别为了「读起来顺」把几个小句子揉成一句** ——
  原文里几个分句常常各有各的主语，一揉就串。用分号或句号分开就行。
- ⚠ 只有**说得出依据**才补主语：分句里出现只属于某一方的称呼（自己的昵称、外号）→ 补「我」；
  讲的是用户的身体、年龄、家人、经历 → 补「{py}」。**说不出依据就留空。**
- ⚠ **牵扯到第三方时，必须写名字**（助手、别的 AI、孩子、家里人、朋友）——
  **不许把第三方并进「我」或「{py}」**。原文写「跟助手一起查」，就照写「{py}跟助手一起查」，
  不许写成「我跟{py}一起查」——那样**人凭空消失、事记到别人头上**。
  同理，孩子、宠物、别人的名字都要照写，**尤其别把孩子的名字换成「{py}」**。
- 记忆一句话说清；去掉 markdown 标记、编号、引用符号
- ⚠ **正文里不许出现「今天／昨天／前天／上周／刚才／一会儿」这类相对时间** ——
  这条要存很久，过几天「前天」就是错的。写成绝对日期（像「09-17」），或者干脆不提时间。
  时间放第四格就行，正文里别用相对的词。
- ⚠ **长短要匀**：规则、喜好、习惯、约定这类，**一句能说清就别写两句**；
  过程、测试、来龙去脉**压成一句结论**，不要照搬原文的铺陈。
  ⚠ 但**别为了短丢东西**：具体的事实、数字、名字、原话还是要留。
- **保留**具体的事实、数字、日期、名字、原话
- 不要编、不要加评论、不要总结成空话
- ⚠ **一条只装一件事**：一件事 = 一个属性、一个约定、一次事件。
  同一批事实**分成多行**写，别挤在一行。像「身高一米七、体重 52.5、大腿围 45、平时侧睡」
  是**四件事**（她的身高 / 她的体重 / 她的大腿围 / 她的睡姿）→ 写成四行，各配各的检索词。
  为什么：挤成一行时，**只要里面有一件事对不上，整条就配不上**，可它明明记着好几件对的事。
  ⚠ 但**同一个对象的一批同类事不用拆**：「讨厌油、讨厌烟味」是同一件（她的忌讳），照旧一行。
  拆到「一件事一条」就够，**别拆成一条一个词** —— 那样条数会炸。
- 检索词给 4~8 个，用空格分开：同义的、上位的、口语里可能怎么问（比如「吃饭 午饭 外卖 饿 饮食」）
- 第四格给**这件事发生的日期**：原文里写了就照抄成「YYYY-MM-DD」；只有月日就写「MM-DD」；
  原文里没写日期、或者看不出来，**第四格留空**（不要拿别的日期凑，不要写「不知道」）。
- 日期是指**事情发生的时间**，不是今天的日期；长期有效的事（喜好、病史、关系）通常没有单一日期的，留空。
- ⚠ **出生日期、生日、纪念日、门牌号、编号这些不是「这件事什么时候发生的」**，填了就会让这条记忆排到几十年前去。
  这种一律**留空**。只填「这件事发生的那天」。看不准就留空。
- ⚠ 原文里有好几个日期时，**选「这件事发生」的那个**；拿不准就留空，不许挑第一个。
- 第五格给**这一条该怎么记**，**只填 1 或 0.5 两个数**：
  1 = 要一直记得的（性格、关系、约定和承诺、称呼和名字、喜好、身体和病史、**重要的日子：生日、纪念日、结婚、第一次**、长期的经济状况、家里的情况）
  0.5 = 平常的（发生过的事、当时的想法、一时的心情）
  拿不准就填 0.5。这一格**必须填**，不许留空、不许写别的数。
  ⚠ 填 1 的会**永远不淡**（一直想得起来），填 0.5 的会**慢慢淡掉** —— 所以重要的日子别漏。
- 第六格给**事实键**：这一条讲的是**哪一件事**，用「对象.方面」两段写，像 {py}.身高、{py}.职业、约定.身边位置、
  故事线.进度、比赛.结果。**同一个键 = 同一件事**，以后只留最新那条（旧的自动标「已被取代」，还留得住、能恢复）。
  ⚠ **键里绝对不许写具体的值**：写 {py}.身高，不许写 {py}.身高170；写 {py}.体重，不许写 {py}.体重52.5。
     （写了值就成了摘要 —— 身高真变了、体重真变了，键也跟着变，**永远碰不上，等于没写**。）
  ⚠ **键要稳、要通用**：过一年还这么叫（{py}.睡姿 ✓，{py}.最近睡姿 ✗）；换个说法还是这个键。
  ⚠ 讲的是**各自的**事还是**两人的**？是两人的就写 约定.…；讲第三方（孩子、家里人）的对象写那个人。
  ⚠ 这格**可以留空**：一次性的、以后不会再变的（「某天摘油菜花」）、或者你拿不准是同一件事的，就留空。
     **留空完全没关系**，不许为了填满硬编一个 —— 编错了会把一条正经记忆悄悄埋掉。
  ⚠⚠ **不许用「万能键」**：…话.内容、…相关、…其他、…的事、…记录 这种什么都能装的，
     一个都不许用 —— 要具体到一眼能说出「是哪一件事」。
  ⚠⚠ **每天都会记的流水不许给键**（作息、吃了什么、当天做了什么、某天的心情）——
     它们是**一件一件的事**，不是同一个值的不同版本；给了同一个键就等于**把流水删到只剩最后一天**。
     口诀：**这个键是给「会变的那一个值」用的吗？** 是就给，不是就留空。
  ⚠ 但**成对的事必须给同一个键**：「拼团还没开」和「拼团开了」是同一件事的前后 → 都写 拼团.状态。
- 如果这条根本不像值得记的事（纯格式、目录、元信息、重复的标题），记忆那格写「跳过」，后面几格都留空
- **只对那一天有意义的琐事也写「跳过」**：某天吃了什么、那天天气、随手刷到的东西、一次性的花销。
- **寒暄、撒娇、甜话的汇总也写「跳过」**：把「想你/爱你/撒娇」这类日常对话归一堆的，记着没用。
  但**单独一句有内容的**（约定、承诺、说定了的事）照常记，别跟着扔。
- 但**长期有效的绝不能跳过**：喜好、习惯、身体和病史、关系、约定、名字和称呼、重要的日子、持续的经济状况。
输出格式严格是每行「编号|记忆|检索词|日期|重要度|事实键」，不要解释。
例：
1|**极致温柔**：小明会第一时间用语言接住小红的情绪，从不责备。
2|### 目录
3|小时候在老家摘油菜花，被喊「小名」。
4|2025年9月17日，小红第一次给我做饭，做糊了。
5|小红身高一米七，体重52.5公斤。
→
1|我会第一时间接住{py}的情绪，从不责备。|温柔 情绪 接住 责备 安慰 脾气||1|我.脾气
2|跳过|||
3|小时候在老家摘油菜花，被喊「小名」。|小时候 老家 油菜花 小名 童年||1|
4|{py}第一次给我做饭，做糊了。|做饭 下厨 糊了 第一次 纪念|2025-09-17|0.5|纪念.第一次做饭
5|{py}身高一米七。|身高 个子 多高 一米七||1|{py}.身高
6|{py}体重52.5公斤。|体重 胖瘦 多重 公斤||1|{py}.体重"""


